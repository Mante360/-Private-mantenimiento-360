-- NO EJECUTAR EN PRODUCCION. Antes de migrar, respaldar datos localStorage,
-- probar la importacion y auditar permisos, accesos e integridad.
BEGIN;

CREATE TABLE users (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name varchar(120) NOT NULL CHECK (length(btrim(name))>=2),
 email varchar(255) NOT NULL UNIQUE CHECK (email=lower(btrim(email))),
 password_hash text NOT NULL,
 role varchar(20) NOT NULL CHECK(role IN ('client','professional','admin')),
 phone varchar(40),
 status varchar(20) NOT NULL DEFAULT 'active' CHECK(status IN ('active','suspended','closed')),
 email_verified_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE user_sessions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 refresh_token_hash text NOT NULL UNIQUE,
 expires_at timestamptz NOT NULL,
 revoked_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX user_sessions_user_idx ON user_sessions(user_id,expires_at);

CREATE TABLE professional_profiles (
 user_id bigint PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 bio text,
 locality varchar(120),
 available boolean NOT NULL DEFAULT true,
 verification_status varchar(20) NOT NULL DEFAULT 'pending'
  CHECK(verification_status IN ('pending','approved','rejected')),
 verified_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now()
);
-- DNI y selfie: solo referencias a almacenamiento PRIVADO CIFRADO, nunca URL publica.
CREATE TABLE professional_verifications (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 professional_id bigint NOT NULL REFERENCES professional_profiles(user_id) ON DELETE CASCADE,
 document_object_key text NOT NULL,
 selfie_object_key text NOT NULL,
 status varchar(20) NOT NULL DEFAULT 'pending'
  CHECK(status IN ('pending','approved','rejected','purged')),
 reviewed_by bigint REFERENCES users(id) ON DELETE SET NULL,
 reviewed_at timestamptz,
 retention_until timestamptz,
 created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE specialties (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name varchar(100) NOT NULL UNIQUE,
 active boolean NOT NULL DEFAULT true
);
CREATE TABLE specialty_services (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 specialty_id bigint NOT NULL REFERENCES specialties(id) ON DELETE RESTRICT,
 name varchar(120) NOT NULL,
 active boolean NOT NULL DEFAULT true,
 UNIQUE(specialty_id,name),
 UNIQUE(id,specialty_id)
);
CREATE TABLE professional_specialties (
 professional_id bigint NOT NULL REFERENCES professional_profiles(user_id) ON DELETE CASCADE,
 specialty_id bigint NOT NULL REFERENCES specialties(id) ON DELETE RESTRICT,
 PRIMARY KEY(professional_id,specialty_id)
);
CREATE TABLE professional_services (
 professional_id bigint NOT NULL,
 specialty_id bigint NOT NULL,
 service_id bigint NOT NULL,
 PRIMARY KEY(professional_id,service_id),
 FOREIGN KEY(professional_id,specialty_id)
  REFERENCES professional_specialties(professional_id,specialty_id) ON DELETE CASCADE,
 FOREIGN KEY(service_id,specialty_id)
  REFERENCES specialty_services(id,specialty_id) ON DELETE RESTRICT
);
CREATE TABLE specialty_suggestions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 suggested_by bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 name varchar(120) NOT NULL,
 status varchar(20) NOT NULL DEFAULT 'pending'
  CHECK(status IN ('pending','approved','rejected')),
 approved_specialty_id bigint REFERENCES specialties(id) ON DELETE SET NULL,
 reviewed_by bigint REFERENCES users(id) ON DELETE SET NULL,
 reviewed_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX specialty_suggestions_status_idx ON specialty_suggestions(status);

CREATE TABLE jobs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 public_code text GENERATED ALWAYS AS ('360-'||lpad(id::text,5,'0')) STORED UNIQUE,
 client_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 specialty_id bigint REFERENCES specialties(id) ON DELETE RESTRICT,
 service_id bigint REFERENCES specialty_services(id) ON DELETE RESTRICT,
 requested_specialty_text varchar(120),
 description text NOT NULL CHECK(length(btrim(description)) BETWEEN 3 AND 3000),
 locality varchar(120) NOT NULL,
 exact_address text, -- Privado: no mostrar a profesionales sin contrato
 status varchar(24) NOT NULL DEFAULT 'requested'
  CHECK(status IN ('requested','quoted','accepted','confirmed','in_progress','completed','cancelled')),
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 completed_at timestamptz,
 CHECK(service_id IS NULL OR specialty_id IS NOT NULL),
 FOREIGN KEY(service_id,specialty_id)
  REFERENCES specialty_services(id,specialty_id) ON DELETE RESTRICT
);
CREATE INDEX jobs_client_idx ON jobs(client_id,created_at DESC);
CREATE INDEX jobs_search_idx ON jobs(specialty_id,service_id,status,created_at DESC);
CREATE TABLE job_attachments (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 job_id bigint NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
 uploaded_by bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 object_key text NOT NULL UNIQUE,
 mime_type varchar(100) NOT NULL,
 byte_size bigint NOT NULL CHECK(byte_size>0),
 created_at timestamptz NOT NULL DEFAULT now()
);

-- Varios presupuestos por trabajo, uno por profesional.
CREATE TABLE job_quotes (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 job_id bigint NOT NULL REFERENCES jobs(id) ON DELETE RESTRICT,
 professional_id bigint NOT NULL REFERENCES professional_profiles(user_id) ON DELETE RESTRICT,
 amount numeric(12,2) NOT NULL CHECK(amount>0),
 description text NOT NULL CHECK(length(btrim(description))>=3),
 warranty_days integer NOT NULL DEFAULT 0 CHECK(warranty_days>=0),
 status varchar(24) NOT NULL DEFAULT 'submitted'
  CHECK(status IN ('submitted','accepted','not_selected','rejected','withdrawn')),
 submitted_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(job_id,professional_id),
 UNIQUE(id,job_id)
);
CREATE INDEX job_quotes_job_idx ON job_quotes(job_id,status);
CREATE INDEX job_quotes_pro_idx ON job_quotes(professional_id,submitted_at DESC);
CREATE UNIQUE INDEX only_one_accepted_quote_idx ON job_quotes(job_id)
 WHERE status='accepted';

-- Un trabajo confirma UNA oferta. No implica pago ni transferencia real.
CREATE TABLE job_contracts (
 job_id bigint PRIMARY KEY REFERENCES jobs(id) ON DELETE RESTRICT,
 quote_id bigint NOT NULL UNIQUE,
 confirmed_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY(quote_id,job_id) REFERENCES job_quotes(id,job_id) ON DELETE RESTRICT
);
CREATE TABLE job_status_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 job_id bigint NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
 actor_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 old_status varchar(24),
 new_status varchar(24) NOT NULL,
 note text,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX job_status_events_job_idx ON job_status_events(job_id,created_at);

CREATE TABLE job_messages (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 job_id bigint NOT NULL REFERENCES jobs(id) ON DELETE RESTRICT,
 sender_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 body text NOT NULL CHECK(length(btrim(body)) BETWEEN 1 AND 5000),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX job_messages_job_idx ON job_messages(job_id,created_at);

-- Garantias hijas, NO trabajos independientes: 360-00173-A, -B, -C.
CREATE TABLE warranty_visits (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 original_job_id bigint NOT NULL REFERENCES jobs(id) ON DELETE RESTRICT,
 suffix varchar(8) NOT NULL CHECK(suffix ~ '^[A-Z]+$'),
 assigned_professional_id bigint REFERENCES professional_profiles(user_id) ON DELETE RESTRICT,
 description text NOT NULL CHECK(length(btrim(description))>=3),
 status varchar(24) NOT NULL DEFAULT 'requested'
  CHECK(status IN ('requested','scheduled','in_progress','completed','cancelled')),
 resolution_note text,
 created_at timestamptz NOT NULL DEFAULT now(),
 completed_at timestamptz,
 UNIQUE(original_job_id,suffix),
 UNIQUE(id,original_job_id)
);
CREATE INDEX warranty_visits_original_idx ON warranty_visits(original_job_id);
CREATE VIEW warranty_display_codes AS
 SELECT w.id AS warranty_id,w.original_job_id,
        j.public_code||'-'||w.suffix AS warranty_code,w.status
 FROM warranty_visits w JOIN jobs j ON j.id=w.original_job_id;

-- Una evaluacion original o de garantia, nunca ambas a la vez.
CREATE TABLE ratings (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 job_id bigint REFERENCES jobs(id) ON DELETE RESTRICT,
 warranty_visit_id bigint REFERENCES warranty_visits(id) ON DELETE RESTRICT,
 client_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 stars smallint NOT NULL CHECK(stars BETWEEN 1 AND 5),
 comment text CHECK(comment IS NULL OR length(comment)<=3000),
 created_at timestamptz NOT NULL DEFAULT now(),
 CHECK((job_id IS NOT NULL) <> (warranty_visit_id IS NOT NULL))
);
CREATE UNIQUE INDEX ratings_original_unique ON ratings(job_id) WHERE job_id IS NOT NULL;
CREATE UNIQUE INDEX ratings_warranty_unique ON ratings(warranty_visit_id)
 WHERE warranty_visit_id IS NOT NULL;

CREATE TABLE claims (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 job_id bigint NOT NULL REFERENCES jobs(id) ON DELETE RESTRICT,
 warranty_visit_id bigint,
 created_by bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 professional_id bigint REFERENCES professional_profiles(user_id) ON DELETE RESTRICT,
 reason varchar(120) NOT NULL,
 description text NOT NULL CHECK(length(btrim(description))>=3),
 status varchar(24) NOT NULL DEFAULT 'open'
  CHECK(status IN ('open','in_review','resolved','dismissed')),
 resolution_note text,
 resolved_by bigint REFERENCES users(id) ON DELETE RESTRICT,
 resolved_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY(warranty_visit_id,job_id)
  REFERENCES warranty_visits(id,original_job_id) ON DELETE RESTRICT
);
CREATE INDEX claims_job_idx ON claims(job_id,status);
CREATE INDEX claims_professional_idx ON claims(professional_id,status);

-- Una restriccion requiere reclamo y decision explicita de Administracion.
CREATE TABLE professional_restrictions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 professional_id bigint NOT NULL REFERENCES professional_profiles(user_id) ON DELETE RESTRICT,
 claim_id bigint NOT NULL REFERENCES claims(id) ON DELETE RESTRICT,
 imposed_by bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 reason text NOT NULL,
 imposed_at timestamptz NOT NULL DEFAULT now(),
 lifted_at timestamptz,
 lifted_by bigint REFERENCES users(id) ON DELETE RESTRICT
);
CREATE UNIQUE INDEX professional_restriction_active ON professional_restrictions(professional_id,claim_id)
 WHERE lifted_at IS NULL;

CREATE TABLE audit_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id bigint REFERENCES users(id) ON DELETE SET NULL,
 action varchar(120) NOT NULL,
 resource_type varchar(80) NOT NULL,
 resource_id varchar(120),
 metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX audit_events_date_idx ON audit_events(created_at DESC);

-- Mapa para migrar localStorage sin repetir trabajos ni garantias.
CREATE TABLE legacy_imports (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 source varchar(80) NOT NULL,
 legacy_key varchar(120) NOT NULL,
 resource_type varchar(60) NOT NULL,
 resource_id bigint NOT NULL,
 imported_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(source,legacy_key,resource_type)
);
COMMIT;
