export async function ensureLabServiceOfferings():Promise<void>{
 const db=await pool.connect();let active=false;
 try{
  await db.query('BEGIN');active=true;
  const identity=await db.query('SELECT current_database() name');
  if(identity.rows[0]?.name!==LAB_SERVICE_DB)throw new Error('Service offerings are lab database only');
  await db.query('SELECT pg_advisory_xact_lock($1::bigint)',[36020261024]);
  await db.query(`CREATE TABLE IF NOT EXISTS lab_service_keywords(
    service_id bigint PRIMARY KEY REFERENCES specialty_services(id) ON DELETE RESTRICT,
    keywords text[] NOT NULL DEFAULT ARRAY[]::text[]
  )`);
  await db.query(`CREATE TABLE IF NOT EXISTS lab_service_declarations(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professional_id bigint NOT NULL REFERENCES professional_profiles(user_id) ON DELETE CASCADE,
    service_id bigint NOT NULL REFERENCES specialty_services(id) ON DELETE RESTRICT,
    status varchar(16) NOT NULL DEFAULT 'pending'
      CHECK(status IN('pending','approved','rejected')),
    requested_at timestamptz NOT NULL DEFAULT now(),
    reviewed_by bigint REFERENCES users(id) ON DELETE SET NULL,
    reviewed_at timestamptz,
    UNIQUE(professional_id,service_id)
  )`);
  await db.query('CREATE INDEX IF NOT EXISTS lab_service_declarations_status_idx ON lab_service_declarations(status,requested_at)');
  for(const item of offered){
    const cat=await db.query('SELECT specialty_id FROM lab_profession_catalog WHERE profession_key=$1',[item.key]);
    if(!cat.rows[0])continue;
    const result=await db.query(`INSERT INTO specialty_services(specialty_id,name,active)
      VALUES($1,$2,true) ON CONFLICT(specialty_id,name) DO UPDATE SET active=true RETURNING id`,
      [cat.rows[0].specialty_id,item.name]);
    await db.query(`INSERT INTO lab_service_keywords(service_id,keywords)
      VALUES($1,$2) ON CONFLICT(service_id) DO UPDATE SET keywords=EXCLUDED.keywords`,
      [result.rows[0].id,item.keywords]);
  }
  await db.query('COMMIT');active=false;
  console.log('Lab service offerings ready. No services assigned automatically.');
 }catch(error){if(active)await db.query('ROLLBACK').catch(()=>undefined);throw error;}
 finally{db.release();}
}
