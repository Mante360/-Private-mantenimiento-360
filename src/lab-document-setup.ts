// Laboratory ONLY: fictitious document metadata for expiry workflow testing.
// Never store DNI images, biometrics, fiscal IDs, addresses or actual documents here.
import {pool} from './db.js';
export const LAB_DOCUMENT_DB='mantenimiento_360_db_pruebas_20261012';

export const documentKinds=[
  {key:'dni',label:'DNI (identidad)',requiresExpiry:true},
  {key:'domicilio',label:'Comprobante de domicilio',requiresExpiry:false},
  {key:'selfie',label:'Captura facial en vivo (futuro)',requiresExpiry:false},
  {key:'matricula',label:'Matrícula o habilitación profesional',requiresExpiry:true},
  {key:'seguro',label:'Seguro profesional',requiresExpiry:true},
  {key:'fiscal',label:'Constancia fiscal ARCA',requiresExpiry:false},
  {key:'antecedentes',label:'Antecedentes (solo si corresponde exigirlos)',requiresExpiry:false}
] as const;
export type DocumentKind=typeof documentKinds[number]['key'];

export async function ensureLabDocumentSchema():Promise<void>{
 const client=await pool.connect();let active=false;
 try{
  await client.query('BEGIN');active=true;
  const db=await client.query('SELECT current_database() AS name');
  if(db.rows[0]?.name!==LAB_DOCUMENT_DB)throw new Error('Document simulation requires named LAB database');
  await client.query('SELECT pg_advisory_xact_lock($1::bigint)',[36020261025]);
  // Public signup still cannot create a subadmin; only a privileged admin action can.
  await client.query('ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_check');
  await client.query(`ALTER TABLE users ADD CONSTRAINT users_role_check
    CHECK(role IN('client','professional','admin','subadmin'))`);
  await client.query(`CREATE TABLE IF NOT EXISTS lab_staff_permissions(
     user_id bigint PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
     document_review boolean NOT NULL DEFAULT false,
     created_by bigint NOT NULL REFERENCES users(id),
     created_at timestamptz NOT NULL DEFAULT now()
   )`);
  await client.query(`CREATE TABLE IF NOT EXISTS lab_document_entries(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professional_id bigint NOT NULL REFERENCES professional_profiles(user_id) ON DELETE CASCADE,
    document_type varchar(32) NOT NULL
      CHECK(document_type IN ('dni','domicilio','selfie','matricula','seguro','fiscal','antecedentes')),
    fictional_reference varchar(120) NOT NULL,
    expires_on date,
    status varchar(24) NOT NULL DEFAULT 'pending'
      CHECK(status IN('pending','needs_more','reviewed_test_only','rejected')),
    reviewer_note varchar(600),
    reviewed_by bigint REFERENCES users(id),
    reviewed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
  )`);
  await client.query(`CREATE INDEX IF NOT EXISTS lab_documents_professional_idx
    ON lab_document_entries(professional_id,document_type,created_at DESC)`);
  await client.query(`CREATE INDEX IF NOT EXISTS lab_documents_pending_idx
    ON lab_document_entries(status,created_at) WHERE status='pending'`);
  await client.query('COMMIT');active=false;
  console.log('Lab-only document expiry ledger and limited reviewer permissions ready. No real files.');
 }catch(error){if(active)await client.query('ROLLBACK').catch(()=>undefined);throw error;}
 finally{client.release();}
}
